// Scans public/images and writes src/config/images.generated.ts
// so the site knows which picture files exist. Run automatically by `npm run dev` and `npm run build`.
// Run by hand after adding pictures:  npm run images
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imagesDir = path.join(root, "public", "images");
const outFile = path.join(root, "src", "config", "images.generated.ts");

// If the same name exists in several formats, the first one in this list wins.
// A real photo (jpg, png, webp, avif) always beats the sample drawing (svg).
const ORDER = [".webp", ".jpg", ".jpeg", ".png", ".avif", ".svg"];

function walk(dir, base = "") {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith("_") || e.name.startsWith(".")) continue; // folders/files starting with _ or . are ignored
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...walk(path.join(dir, e.name), rel));
    else if (ORDER.includes(path.extname(e.name).toLowerCase())) out.push(rel);
  }
  return out;
}

export function build({ quiet = false } = {}) {
  const best = new Map(); // "services/pipe-leakage-repair" -> "services/pipe-leakage-repair.jpg"
  for (const rel of walk(imagesDir)) {
    const ext = path.extname(rel).toLowerCase();
    const key = rel.slice(0, -ext.length).toLowerCase();
    const cur = best.get(key);
    if (!cur || ORDER.indexOf(ext) < ORDER.indexOf(path.extname(cur).toLowerCase())) best.set(key, rel);
  }
  const keys = [...best.keys()].sort();
  const lines = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify("/images/" + best.get(k))},`);
  const body = `// AUTO-GENERATED by scripts/build-images.mjs - do not edit by hand.\n// Lists every picture found in public/images. Re-created on \`npm run dev\`, \`npm run build\` and \`npm run images\`.\nexport const IMAGE_FILES: Record<string, string> = {\n${lines.join("\n")}\n};\n`;
  const prev = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (prev !== body) fs.writeFileSync(outFile, body);

  if (!quiet) {
    const own = keys.filter((k) => !best.get(k).toLowerCase().endsWith(".svg"));
    console.log(`[images] ${keys.length} pictures found, ${own.length} of them are your own photos (the rest are sample drawings).`);
  }
  return keys.length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
